#!/usr/bin/env python
"""Update the translation catalogs (.po) after the English pages change.

The English pages in ``docs/source/`` are the only source text. Their
translations live in ``docs/locale/<language>/LC_MESSAGES/<page>.po``, one file
per page, each entry holding an English text (``msgid``) and its translation
(``msgstr``). This script

1. asks Sphinx to extract the texts of every page (the gettext builder),
2. merges them into the catalog of each language: translations of unchanged
   texts are kept, new texts appear untranslated and texts that changed a
   little are marked ``fuzzy`` so the translator reviews them,
3. writes the catalogs without source locations, so a change in the English
   text produces a small diff.

A text that is untranslated or fuzzy is shown in English in the translated site.
The API page is generated from the ``.m`` comments and stays in English: only
its own headings and sentences are translated.

Usage:
    python docs/tools/update_translations.py               update the catalogs
    python docs/tools/update_translations.py --status      only report what is left
    python docs/tools/update_translations.py --languages es pt
"""
import argparse
import io
import re
import subprocess
import sys
import tempfile
from pathlib import Path

from babel.messages.catalog import Catalog
from babel.messages.pofile import read_po, write_po

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs" / "source"
LOCALE = ROOT / "docs" / "locale"
LANGUAGES = ["es", "pt", "it"]
NAMES = {"es": "Spanish", "pt": "Portuguese", "it": "Italian"}


def extract(target):
    """Run the gettext builder; return {page: Catalog} for every page."""
    subprocess.run(
        [sys.executable, "-m", "sphinx", "-q", "-b", "gettext",
         "-D", "gettext_compact=0", "-D", "gettext_location=1", str(SOURCE), str(target)],
        check=True,
    )
    catalogs = {}
    for pot in sorted(Path(target).rglob("*.pot")):
        page = pot.relative_to(target).with_suffix("").as_posix()
        if page == "sphinx":          # texts of the theme and of Sphinx itself
            continue
        with open(pot, "rb") as handle:
            catalogs[page] = read_po(handle)
    return catalogs


def own_texts_only(page, catalog):
    """The API page is mostly generated docstrings: keep only the texts written in its .rst."""
    if page != "api/index":
        return catalog
    kept = Catalog(project=catalog.project, version=catalog.version, charset="utf-8")
    for message in catalog:
        if message.id and any(str(loc[0]).replace("\\", "/").endswith("api/index.rst")
                              for loc in message.locations):
            kept.add(message.id, locations=message.locations)
    return kept


def merge(language, page, template):
    """Return the catalog of one page and language, merged with its template."""
    path = LOCALE / language / "LC_MESSAGES" / (page + ".po")
    if path.is_file():
        with open(path, "rb") as handle:
            catalog = read_po(handle, locale=language)
    else:
        catalog = Catalog(locale=language, project="LDEM-MATLAB", charset="utf-8")
    catalog.update(template, no_fuzzy_matching=False)
    for message in catalog:
        message.locations = []
    catalog.fuzzy = False            # the header of the catalog is not a translation to review
    catalog.project = "LDEM-MATLAB"
    catalog.version = ""
    catalog.msgid_bugs_address = ""
    catalog.last_translator = ""
    catalog.language_team = ""
    catalog.header_comment = (
        "# Translation of the LDEM-MATLAB documentation (%s).\n"
        "# Generated by docs/tools/update_translations.py: edit only the msgstr entries." % language
    )
    return path, catalog


def save(path, catalog):
    """Write a catalog without the dates and the version, so an update only changes real text."""
    path.parent.mkdir(parents=True, exist_ok=True)
    buffer = io.BytesIO()
    write_po(buffer, catalog, width=88, ignore_obsolete=True, include_previous=False)
    text = buffer.getvalue().decode("utf-8")
    text = re.sub(r'"(POT-Creation-Date|PO-Revision-Date): [^\n]*\\n"\n', "", text)
    text = text.replace('"Project-Id-Version: LDEM-MATLAB \\n"', '"Project-Id-Version: LDEM-MATLAB\\n"')
    path.write_bytes(text.encode("utf-8"))


def count(catalog):
    translated = fuzzy = missing = 0
    for message in catalog:
        if not message.id:
            continue
        if not message.string or (isinstance(message.string, (list, tuple)) and not any(message.string)):
            missing += 1
        elif message.fuzzy:
            fuzzy += 1
        else:
            translated += 1
    return translated, fuzzy, missing


def status(languages):
    print("%-10s %12s %8s %12s" % ("language", "translated", "fuzzy", "untranslated"))
    for language in languages:
        total = [0, 0, 0]
        worst = []
        for path in sorted((LOCALE / language / "LC_MESSAGES").rglob("*.po")):
            with open(path, "rb") as handle:
                numbers = count(read_po(handle, locale=language))
            total = [a + b for a, b in zip(total, numbers)]
            if numbers[1] or numbers[2]:
                worst.append((path.relative_to(LOCALE / language / "LC_MESSAGES").as_posix(), numbers))
        print("%-10s %12d %8d %12d" % (NAMES.get(language, language), *total))
        for name, numbers in worst:
            print("    %-24s fuzzy %d, untranslated %d" % (name, numbers[1], numbers[2]))
    print("\nSome untranslated entries are intentional: code lines, names and tables that read "
          "the same in every language are left empty and shown as they are.")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--languages", nargs="+", default=LANGUAGES, choices=LANGUAGES)
    parser.add_argument("--status", action="store_true", help="only report what is left to translate")
    args = parser.parse_args()
    if not args.status:
        with tempfile.TemporaryDirectory() as tmp:
            catalogs = extract(tmp)
        for language in args.languages:
            for page, template in catalogs.items():
                path, catalog = merge(language, page, own_texts_only(page, template))
                save(path, catalog)
        print("Catalogs updated in", LOCALE)
    status(args.languages)


if __name__ == "__main__":
    main()
