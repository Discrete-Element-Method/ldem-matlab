function text = convertLegacyInput(dataPath, casePath, options)
%CONVERTLEGACYINPUT  Convert a DATA0.DAT input file into a case file (.ldem).
%
%   text = ldem.io.convertLegacyInput(dataPath, casePath) reads the legacy
%   input file with ldem.io.readInputFile and writes the equivalent case
%   file: named keys, units, comments, M N L converted to modules, the control
%   nodes with their coordinates, and the scenario of the TEST number with its
%   default values. The case file gives exactly the same ldem.Parameters as
%   ldem.Parameters.fromFile(dataPath).
%
%   Values that the legacy file does not contain can be given as options. The
%   converter never guesses them: in the examples of this repository the value
%   OU2 of the DATA0.DAT is the number of the tracked bar, but the legacy code
%   does not use it, so it is only copied into a comment.
%
%   Inputs:
%     dataPath  Path of the DATA0.DAT file.
%     casePath  Path of the .ldem file to create ("" to only return the text).
%
%   Name-value options:
%     RandomFieldFile  File with the random field (enables scatter type "file").
%     TrackedBar       Bar whose strain history is stored (see monitor.bar).
%     Scenario         Scenario object (default: the one of the TEST number).
%     Title            Title for the case file (default: the DATA0 file name).
%     Authors          String array of authors.
%     OutputFolder     Value of output.folder (default "output").
%
%   Output:
%     text  Content of the case file.
%
%   Example:
%       ldem.io.convertLegacyInput("examples/beam_102/DATA0.DAT", ...
%           "examples/beam_102/case.ldem");
%
%   See also ldem.io.readCase, ldem.io.readInputFile, ldem.io.writeCase.

arguments
    dataPath (1,1) string
    casePath (1,1) string
    options.RandomFieldFile (1,1) string = ""
    options.TrackedBar = []
    options.Scenario = []
    options.Title (1,1) string = ""
    options.Authors (1,:) string = string.empty
    options.OutputFolder (1,1) string = "output"
end

overrides = {};
if strlength(options.RandomFieldFile) > 0
    overrides = [overrides, {'randomFieldFile', options.RandomFieldFile}];
end
if ~isempty(options.TrackedBar)
    overrides = [overrides, {'trackedBar', options.TrackedBar}];
end
params = ldem.Parameters.fromFile(dataPath, overrides{:});
if ~isempty(options.TrackedBar)
    output = params.output;
    output.trackedBarEvery = 1;
    params.output = output;
end

[~, dataName, dataExt] = fileparts(dataPath);
title = options.Title;
if title == ""
    title = "Converted from " + string(dataName) + string(dataExt);
end
header = "Case file generated by ldem.io.convertLegacyInput from " + string(dataName) + string(dataExt) + ".";
ou2 = legacyOu2(dataPath);
if ~isnan(ou2) && isempty(options.TrackedBar)
    header(end+1) = "The legacy value OU2 was " + ldem.schema.shortestText(ou2) + ...
        " (not used by ldem). If it is the number of the tracked bar, set [monitor.bar] tracked.";
end

text = ldem.io.writeCase(casePath, params, options.Scenario, ...
    Title = title, Authors = options.Authors, Header = header, ...
    OutputFolder = options.OutputFolder);
end

function value = legacyOu2(dataPath)
%LEGACYOU2  The OU2 value of a DATA0.DAT file, or NaN if it cannot be read.
try
    lines = splitlines(string(fileread(dataPath)));
    tokens = strings(0, 1);
    for k = 1:numel(lines)
        word = strtok(strtrim(lines(k)));
        if strlength(word) > 0
            tokens(end+1, 1) = word; %#ok<AGROW>
        end
    end
    nControl = str2double(tokens(13));
    value = str2double(tokens(13 + nControl + 1));
catch
    value = NaN;
end
end
