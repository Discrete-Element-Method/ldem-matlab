function schema = caseSchema()
%CASESCHEMA  Table of the keys of a case file (.ldem), the single source of truth.
%
%   schema = ldem.schema.caseSchema() returns one row per key. The reader
%   (ldem.io.readCase), the writer (ldem.io.writeCase) and the template are
%   all driven by this table, so adding a key to the file format means adding
%   a row here and, when it maps to an ldem.Parameters property, nothing else.
%
%   Fields of every row:
%
%     path       Section and key, for example "material.young_modulus".
%     kind       How the value is read: integer, number, quantity (number with a unit), string, stringlist, path, intlist, numberlist, bool, enum, stepOrAuto or cadence.
%     dimension  Dimension of a "quantity", see ldem.schema.unitTable.
%     prop       Name of the ldem.Parameters property it sets ("" if the key needs special handling).
%     required   True if the file must contain the key.
%     legacy     Variable of the legacy DATA0.DAT file it replaces.
%     doc        One-line description, used for the comments of the template.
%     choices    Allowed words of an "enum", separated by "|".
%
%   The keys of the [scenario] section other than "type" belong to the chosen
%   scenario class and are described by ldem.scenarios.registry.
%
%   Output:
%     schema  Struct array (one element per key).
%
%   Example:
%       schema = ldem.schema.caseSchema();
%       schema(strcmp({schema.path}, "mesh.module_size")).legacy   % "LCO"
%
%   See also ldem.io.readCase, ldem.io.writeCase, ldem.scenarios.registry.

fields = ["path" "kind" "dimension" "prop" "required" "legacy" "doc" "choices"];
rows = {
    "format", "integer", "number", "", false, "", ...
        "Version of the case-file format (currently 1).", ""
    "title", "string", "number", "", false, "", ...
        "Free text title of the case.", ""
    "authors", "stringlist", "number", "", false, "", ...
        "Names of the authors.", ""

    "mesh.module_size", "quantity", "length", "moduleLength", false, "LCO", ...
        "Edge length of each cubic module.", ""
    "mesh.modules", "intlist", "number", "nModules", true, "M N L", ...
        "Cubic modules along x, y and z (M N L of the legacy file count nodes: one more).", ""
    "mesh.perturbation", "number", "number", "meshPerturbation", false, "", ...
        "Random node displacement as a fraction of the module size; 0 = regular lattice.", ""
    "mesh.seed", "integer", "number", "seed", false, "SEED", ...
        "Seed of the mesh perturbation (the random field has its own seed).", ""

    "material.law", "enum", "number", "", false, "", ...
        "Constitutive law of the bars.", "bilinear"
    "material.young_modulus", "quantity", "pressure", "youngModulus", false, "YNG", ...
        "Young's modulus.", ""
    "material.poisson_ratio", "number", "number", "poissonRatio", false, "PSN", ...
        "Poisson's ratio, from 0 up to less than 0.5.", ""
    "material.density", "quantity", "density", "density", false, "ROH", ...
        "Mass density.", ""
    "material.fracture_energy", "quantity", "toughness", "fractureEnergy", false, "GFR", ...
        "Specific fracture energy.", ""
    "material.critical_distance", "quantity", "length", "criticalDistance", false, "DEQ", ...
        "Equivalent (critical) distance.", ""
    "material.failure_area_factor", "number", "number", "failureAreaFactor", false, "CAF", ...
        "Fraction of the module face that fails per bar.", ""

    "material.scatter.type", "enum", "number", "", false, "", ...
        "Scatter of the critical strain: none, file (one multiplier per bar) or generated.", ...
        "none|file|generated"
    "material.scatter.file", "path", "number", "randomFieldFile", false, "", ...
        "Text file with one multiplier per bar, relative to this file.", ""
    "material.scatter.cv", "number", "number", "randomFieldCv", false, "", ...
        "Coefficient of variation of the generated field (1e-4 to 3).", ""
    "material.scatter.correlation_length", "numberlist", "number", ...
        "randomFieldCorrelationLength", false, "", ...
        "Correlation length of the generated field in modules: one value or [x, y, z].", ""
    "material.scatter.seed", "integer", "number", "randomFieldSeed", false, "", ...
        "Seed of the generated field.", ""

    "time.step", "stepOrAuto", "time", "dt", false, "DT", ...
        "Integration time step, or auto (0.9 times the critical step).", ""
    "time.duration", "quantity", "time", "totalTime", true, "TTOT", ...
        "Total simulated time.", ""

    "damping.type", "enum", "number", "", false, "", ...
        "Damping model.", "mass_proportional"
    "damping.initial", "quantity", "rate", "dampingInitial", false, "DF1", ...
        "Mass-proportional damping before switch_time.", ""
    "damping.final", "quantity", "rate", "dampingFinal", false, "DF2", ...
        "Mass-proportional damping after switch_time.", ""
    "damping.switch_time", "quantity", "time", "dampingSwitchTime", false, "TDAF", ...
        "Time at which the damping changes from initial to final.", ""
    "damping.constitutive", "quantity", "time", "constitutiveDamping", false, "CON", ...
        "Stiffness-proportional damping inside the bar law.", ""

    "scenario.type", "enum", "number", "", true, "TEST", ...
        "Test case (see ldem.scenarios.registry); its other keys follow.", ""

    "monitor.node.id", "integer", "number", "", false, "NCON", ...
        "Number of a node whose motion is recorded.", ""
    "monitor.node.at", "numberlist", "number", "", false, "", ...
        "Position [x, y, z] in modules; the nearest node is recorded.", ""
    "monitor.node.name", "string", "number", "", false, "", ...
        "Label of the node.", ""
    "monitor.bar.tracked", "integer", "number", "trackedBar", false, "OU9", ...
        "Number of the bar whose strain history is stored at every step.", ""

    "output.folder", "string", "number", "", false, "", ...
        "Output folder, relative to the case file.", ""
    "output.mat", "bool", "number", "", false, "", ...
        "Write results.mat.", ""
    "output.ansys", "bool", "number", "", false, "", ...
        "Write ANSYS macro files (needs snapshots.every > 0).", ""
    "output.vtk", "bool", "number", "", false, "", ...
        "Write VTK files for ParaView (needs snapshots.every > 0).", ""
    "output.snapshots.every", "cadence", "number", "snapshotEvery", false, "OU3", ...
        "Steps or time between full-field snapshots; 0 = never.", ""
    "output.control_nodes.every", "cadence", "number", "controlNodesEvery", false, "OU6", ...
        "Steps or time between records of the control nodes and reactions; 0 = never.", ""
    "output.energy.every", "cadence", "number", "energyEvery", false, "OU8", ...
        "Steps or time between records of the energies; 0 = never.", ""
    };

schema = cell2struct(rows, fields, 2);
end
