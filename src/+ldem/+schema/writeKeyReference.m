function text = writeKeyReference(path)
%WRITEKEYREFERENCE  Write the reference of the case-file keys, generated from the schema.
%
%   text = ldem.schema.writeKeyReference(path) builds the tables of keys that the
%   user guide includes (docs/source/case-keys.inc): one table per section with
%   the key, the kind of value and its units, the default, the variable of the
%   legacy DATA0.DAT it replaces and the description. Everything comes from
%   ldem.schema.caseSchema and the defaults of ldem.Parameters, so the guide
%   cannot disagree with the reader. The text is reStructuredText.
%
%   After changing the schema, regenerate the file from the repository root:
%
%       ldem.schema.writeKeyReference("docs/source/case-keys.inc");
%
%   A test compares the file with the generated text and fails when they differ.
%
%   Input:
%     path  File to write ("" to only return the text).
%
%   Output:
%     text  The reStructuredText, a string scalar.
%
%   See also ldem.schema.caseSchema, ldem.io.writeTemplate.

arguments
    path (1,1) string = ""
end

schema = ldem.schema.caseSchema();
defaults = ldem.Parameters();
arrayTables = ["monitor.node" "support" "load" "sweep"];

lines = [
    ".. This file is generated by ldem.schema.writeKeyReference from ldem.schema.caseSchema."
    ".. Do not edit it by hand: change the schema and generate it again."
    ""];

paths = string({schema.path});
sections = strings(size(paths));
for k = 1:numel(paths)
    dot = find(char(paths(k)) == '.', 1, 'last');
    if isempty(dot)
        sections(k) = "";
    else
        sections(k) = extractBefore(paths(k), dot);
    end
end

for section = unique(sections, 'stable')
    if section == ""
        title = "(top level)";
    elseif any(section == arrayTables)
        title = "[[" + section + "]]";
    else
        title = "[" + section + "]";
    end
    lines = [lines; ".. rubric:: ``" + title + "``"; ""; ...
        ".. list-table::"; "   :header-rows: 1"; "   :widths: 18 24 12 8 38"; ""; ...
        "   * - Key"; "     - Value"; "     - Default"; "     - Legacy"; "     - Description"]; %#ok<AGROW>
    for k = find(sections == section)
        row = schema(k);
        key = extractAfter(paths(k), strlength(section) + double(section ~= ""));
        legacy = string(row.legacy);
        if legacy == ""
            legacy = "(none)";
        end
        lines = [lines; ...
            "   * - ``" + key + "``"; ...
            "     - " + escape(valueText(row)); ...
            "     - " + escape(defaultText(row, defaults)); ...
            "     - " + escape(legacy); ...
            "     - " + escape(string(row.doc))]; %#ok<AGROW>
    end
    lines = [lines; ""]; %#ok<AGROW>
end

text = strjoin(lines, newline);
text = regexprep(text, '\n+$', '') + newline;
if strlength(path) > 0
    fid = fopen(path, 'w', 'n', 'UTF-8');
    if fid == -1
        error('ldem:io:cannotOpenFile', 'Cannot create "%s".', path);
    end
    fprintf(fid, '%s', text);
    fclose(fid);
end
end

function t = valueText(row)
switch string(row.kind)
    case "integer"
        t = "integer";
    case "number"
        t = "number";
    case "quantity"
        names = ldem.schema.unitTable(string(row.dimension));
        t = "number + unit (" + strjoin(names, ", ") + ")";
    case "string"
        t = "text";
    case "stringlist"
        t = "list of texts";
    case "path"
        t = "file path";
    case "intlist"
        t = "list of integers";
    case "numberlist"
        t = "list of numbers";
    case "bool"
        t = "true or false";
    case "enum"
        t = strjoin(split(string(row.choices), "|").', ", ");
    case "stepOrAuto"
        t = "time, or auto";
    case "cadence"
        t = "steps or time (0 = never)";
    case "coordinate"
        t = "modules: number, text or [lo, hi]";
    case "loadQuantity"
        t = "N, N/s, m or m/s, by type";
    otherwise
        t = string(row.kind);
end
end

function t = defaultText(row, defaults)
manual = struct( ...
    'material_scatter_type', '"none"', 'support_nodes', '"all"', 'load_nodes', '"all"', ...
    'time_step', '"auto"', 'output_mat', 'true', 'output_ansys', 'false', 'output_vtk', 'false', ...
    'output_folder', 'no files', 'sweep_mode', '"product"', 'support_reaction', 'false', ...
    'load_reaction', 'false', 'monitor_bar_tracked', 'off', 'format', '1');
name = strrep(string(row.path), ".", "_");
if row.required
    t = "required";
elseif isfield(manual, name)
    t = string(manual.(name));
elseif string(row.prop) ~= "" && isprop(defaults, row.prop)
    if string(row.kind) == "cadence"
        value = defaults.output.(row.prop);
    else
        value = defaults.(row.prop);
    end
    t = formatDefault(row, value);
else
    t = "(none)";
end
end

function t = formatDefault(row, value)
switch string(row.kind)
    case "quantity"
        t = ldem.schema.formatQuantity(value, string(row.dimension));
    case "cadence"
        if value == 0
            t = "0";
        else
            t = string(value) + " steps";
        end
    case {"enum", "string", "path"}
        if strlength(string(value)) == 0
            t = "(none)";
        else
            t = '"' + string(value) + '"';
        end
    case "numberlist"
        t = "[" + strjoin(arrayfun(@ldem.schema.shortestText, value), ", ") + "]";
    otherwise
        t = ldem.schema.shortestText(double(value));
end
end

function t = escape(s)
%ESCAPE  Make a text safe inside a reStructuredText table cell.
t = replace(replace(string(s), "\", "\\"), "_", "\_");
t = replace(replace(t, "*", "\*"), "|", "\|");
end
